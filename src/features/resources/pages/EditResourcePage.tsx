"use client";

import React, { useEffect, useState } from "react";
import { useParams, useRouter } from "next/navigation";
import { ArrowLeft } from "lucide-react";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";

import {
  useResourceQuery,
  useUpdateResourceMutation,
} from "../hooks/useResources";

import { ResourceForm } from "../components/ResourceForm";

import type {
  CreateResourceFormValues,
  UpdateResourceFormValues,
} from "../schemas";
import { storageService } from "@/lib/firebase/storage";

export const EditResourcePage: React.FC = () => {
  const router = useRouter();
  const params = useParams();

  const resourceId = typeof params?.id === "string" ? params.id : "";

  const [isSubmitting, setIsSubmitting] = useState(false);

  const {
    data: resource,
    isLoading,
    isError,
    error,
  } = useResourceQuery(resourceId);

  const { mutate: updateResource } = useUpdateResourceMutation();

  /**
   * Show API error
   */
  useEffect(() => {
    if (!isError) {
      return;
    }

    toast.error(
      error instanceof Error ? error.message : "Failed to load resource",
    );
  }, [isError, error]);

  /**
   * Cancel editing
   */
  const handleCancel = () => {
    router.push("/resources");
  };

  /**
   * Submit updated resource
   */
  const handleSubmit = async (
    values: CreateResourceFormValues,
    thumbnailFile?: File,
  ) => {
    if (!resourceId) {
      toast.error("Resource ID is missing");
      return;
    }

    if (!resource) {
      toast.error("Resource could not be loaded");
      return;
    }

    try {
      setIsSubmitting(true);

      const thumbnail = thumbnailFile
        ? await storageService.uploadFile("resources/thumbnails", thumbnailFile)
        : values.thumbnail;

      /*
       * Only send editable resource fields.
       *
       * creatorId is preserved from the existing resource.
       * updatedAt is generated by the backend/repository.
       */
      const submissionData: UpdateResourceFormValues = {
        title: values.title,
        description: values.description,
        category: values.category,
        fileType: values.fileType,
        thumbnail,
        url: values.url,
        isPremium: values.isPremium,

        creatorId: resource.creatorId,
      };

      updateResource(
        {
          id: resourceId,
          data: submissionData,
        },
        {
          onSuccess: (updatedResource) => {
            setIsSubmitting(false);

            toast.success(
              `Resource "${updatedResource.title}" updated successfully!`,
            );

            router.push("/resources");
          },

          onError: (error: unknown) => {
            setIsSubmitting(false);

            const message =
              error instanceof Error
                ? error.message
                : "Failed to update resource";

            toast.error(message);
          },
        },
      );
    } catch (error) {
      setIsSubmitting(false);
      toast.error(
        error instanceof Error ? error.message : "Failed to upload thumbnail",
      );
    }
  };

  /**
   * Missing resource ID
   */
  if (!resourceId) {
    return (
      <div className="space-y-4 p-6">
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="icon"
            onClick={handleCancel}
            className="h-10 w-10"
          >
            <ArrowLeft className="h-5 w-5" />
          </Button>

          <div>
            <h1 className="text-3xl font-extrabold tracking-tight">
              Edit Resource
            </h1>

            <p className="text-muted-foreground text-sm font-medium">
              No resource ID was provided.
            </p>
          </div>
        </div>
      </div>
    );
  }

  /**
   * Loading state
   */
  if (isLoading) {
    return (
      <div className="animate-fade-in space-y-6 p-6">
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="icon"
            onClick={handleCancel}
            className="h-10 w-10"
          >
            <ArrowLeft className="h-5 w-5" />
          </Button>

          <div>
            <h1 className="text-3xl font-extrabold tracking-tight">
              Edit Resource
            </h1>

            <p className="text-muted-foreground text-sm font-medium">
              Loading resource...
            </p>
          </div>
        </div>

        <div className="bg-card border-border rounded-xl border p-6 shadow-sm">
          <div className="animate-pulse space-y-6">
            <div className="bg-muted h-10 rounded-md" />

            <div className="bg-muted h-24 rounded-md" />

            <div className="grid grid-cols-1 gap-4 md:grid-cols-3">
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
            </div>

            <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
            </div>
          </div>
        </div>
      </div>
    );
  }

  /**
   * Error / not found state
   */
  if (isError || !resource) {
    return (
      <div className="animate-fade-in space-y-6 p-6">
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="icon"
            onClick={handleCancel}
            className="h-10 w-10"
          >
            <ArrowLeft className="h-5 w-5" />
          </Button>

          <div>
            <h1 className="text-3xl font-extrabold tracking-tight">
              Edit Resource
            </h1>

            <p className="text-muted-foreground text-sm font-medium">
              The requested resource could not be found.
            </p>
          </div>
        </div>

        <div className="bg-card border-border rounded-xl border p-6 shadow-sm">
          <p className="text-muted-foreground">
            Unable to load this resource. It may have been deleted or you may
            not have permission to edit it.
          </p>

          <Button
            type="button"
            variant="outline"
            className="mt-4"
            onClick={handleCancel}
          >
            Back to Resources
          </Button>
        </div>
      </div>
    );
  }

  /**
   * Form values
   */
  const defaultValues: Partial<CreateResourceFormValues> = {
    title: resource.title ?? "",
    description: resource.description ?? "",
    category: resource.category as CreateResourceFormValues["category"],
    fileType: resource.fileType as CreateResourceFormValues["fileType"],
    thumbnail: resource.thumbnail ?? "",
    url: resource.url ?? "",
    isPremium: resource.isPremium ?? false,
    creatorId: resource.creatorId ?? "",
  };

  /**
   * Loaded state
   */
  return (
    <div className="animate-fade-in space-y-6 p-6">
      {/* Back navigation */}
      <div className="flex items-center gap-2">
        <Button
          variant="ghost"
          size="icon"
          onClick={handleCancel}
          disabled={isSubmitting}
          className="h-10 w-10"
        >
          <ArrowLeft className="h-5 w-5" />
        </Button>

        <div>
          <h1 className="text-3xl font-extrabold tracking-tight">
            Edit Resource
          </h1>

          <p className="text-muted-foreground text-sm font-medium">
            Update the resource details and settings.
          </p>
        </div>
      </div>

      {/* Form */}
      <div className="bg-card border-border rounded-xl border p-6 shadow-sm">
        <ResourceForm
          onSubmit={handleSubmit}
          onCancel={handleCancel}
          isSubmitting={isSubmitting}
          defaultValues={defaultValues}
          isEditMode
        />
      </div>
    </div>
  );
};

export default EditResourcePage;
