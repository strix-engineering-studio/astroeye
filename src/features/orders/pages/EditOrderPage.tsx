"use client";

import React, { useEffect, useState } from "react";
import { useParams, useRouter } from "next/navigation";
import { ArrowLeft } from "lucide-react";
import { toast } from "sonner";

import { Button } from "@/components/ui/button";

import { useOrderQuery, useUpdateOrderMutation } from "../hooks/useOrders";

import { OrderForm } from "../components/OrderForm";

import type { CreateOrderFormValues, UpdateOrderFormValues } from "../schemas";

export const EditOrderPage: React.FC = () => {
  const router = useRouter();
  const params = useParams();

  const orderId = typeof params?.id === "string" ? params.id : "";

  const [isSubmitting, setIsSubmitting] = useState(false);

  const { data: order, isLoading, isError, error } = useOrderQuery(orderId);

  const { mutate: updateOrder } = useUpdateOrderMutation();

  /**
   * Show API error
   */
  useEffect(() => {
    if (!isError) {
      return;
    }

    toast.error(
      error instanceof Error ? error.message : "Failed to load order",
    );
  }, [isError, error]);

  /**
   * Cancel editing
   */
  const handleCancel = () => {
    router.push("/orders");
  };

  /**
   * Submit updated order
   */
  const handleSubmit = async (values: CreateOrderFormValues) => {
    if (!orderId) {
      toast.error("Order ID is missing");
      return;
    }

    if (!order) {
      toast.error("Order could not be loaded");
      return;
    }

    try {
      setIsSubmitting(true);

      /*
       * Only send editable order fields.
       *
       * Order identity fields such as:
       * - userId
       * - resourceId
       * - creatorId
       *
       * are preserved from the existing order.
       *
       * updatedAt is generated by the backend/repository.
       */
      const submissionData: UpdateOrderFormValues = {
        title: values.title,
        amount: values.amount,
        currency: values.currency,
        status: values.status,
        paymentId: values.paymentId,
        paymentMethod: values.paymentMethod,
      };

      updateOrder(
        {
          id: orderId,
          data: submissionData,
        },
        {
          onSuccess: (updatedOrder) => {
            setIsSubmitting(false);

            toast.success(
              `Order "${updatedOrder.title}" updated successfully!`,
            );

            router.push("/orders");
          },

          onError: (error: unknown) => {
            setIsSubmitting(false);

            const message =
              error instanceof Error ? error.message : "Failed to update order";

            toast.error(message);
          },
        },
      );
    } catch (error) {
      setIsSubmitting(false);

      toast.error(
        error instanceof Error ? error.message : "Failed to update order",
      );
    }
  };

  /**
   * Missing order ID
   */
  if (!orderId) {
    return (
      <div className="space-y-4 p-6">
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="icon"
            onClick={handleCancel}
            className="h-10 w-10"
          >
            <ArrowLeft className="h-5 w-5" />
          </Button>

          <div>
            <h1 className="text-3xl font-extrabold tracking-tight">
              Edit Order
            </h1>

            <p className="text-muted-foreground text-sm font-medium">
              No order ID was provided.
            </p>
          </div>
        </div>
      </div>
    );
  }

  /**
   * Loading state
   */
  if (isLoading) {
    return (
      <div className="animate-fade-in space-y-6 p-6">
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="icon"
            onClick={handleCancel}
            className="h-10 w-10"
          >
            <ArrowLeft className="h-5 w-5" />
          </Button>

          <div>
            <h1 className="text-3xl font-extrabold tracking-tight">
              Edit Order
            </h1>

            <p className="text-muted-foreground text-sm font-medium">
              Loading order...
            </p>
          </div>
        </div>

        <div className="bg-card border-border rounded-xl border p-6 shadow-sm">
          <div className="animate-pulse space-y-6">
            <div className="bg-muted h-10 rounded-md" />

            <div className="grid grid-cols-1 gap-4 md:grid-cols-3">
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
            </div>

            <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
            </div>

            <div className="grid grid-cols-1 gap-4 md:grid-cols-2">
              <div className="bg-muted h-10 rounded-md" />
              <div className="bg-muted h-10 rounded-md" />
            </div>
          </div>
        </div>
      </div>
    );
  }

  /**
   * Error / not found state
   */
  if (isError || !order) {
    return (
      <div className="animate-fade-in space-y-6 p-6">
        <div className="flex items-center gap-2">
          <Button
            variant="ghost"
            size="icon"
            onClick={handleCancel}
            className="h-10 w-10"
          >
            <ArrowLeft className="h-5 w-5" />
          </Button>

          <div>
            <h1 className="text-3xl font-extrabold tracking-tight">
              Edit Order
            </h1>

            <p className="text-muted-foreground text-sm font-medium">
              The requested order could not be found.
            </p>
          </div>
        </div>

        <div className="bg-card border-border rounded-xl border p-6 shadow-sm">
          <p className="text-muted-foreground">
            Unable to load this order. It may have been deleted or you may not
            have permission to edit it.
          </p>

          <Button
            type="button"
            variant="outline"
            className="mt-4"
            onClick={handleCancel}
          >
            Back to Orders
          </Button>
        </div>
      </div>
    );
  }

  /**
   * Form values
   */
  const defaultValues: Partial<CreateOrderFormValues> = {
    userId: order.userId ?? "",
    resourceId: order.resourceId ?? "",
    creatorId: order.creatorId ?? "",

    title: order.title ?? "",
    amount: order.amount ?? 0,
    currency: order.currency ?? "INR",

    status: order.status,

    paymentId: order.paymentId ?? "",
    paymentMethod: order.paymentMethod ?? "",
  };

  /**
   * Loaded state
   */
  return (
    <div className="animate-fade-in space-y-6 p-6">
      {/* Back navigation */}
      <div className="flex items-center gap-2">
        <Button
          variant="ghost"
          size="icon"
          onClick={handleCancel}
          disabled={isSubmitting}
          className="h-10 w-10"
        >
          <ArrowLeft className="h-5 w-5" />
        </Button>

        <div>
          <h1 className="text-3xl font-extrabold tracking-tight">Edit Order</h1>

          <p className="text-muted-foreground text-sm font-medium">
            Update the order details and payment information.
          </p>
        </div>
      </div>

      {/* Form */}
      <div className="bg-card border-border rounded-xl border p-6 shadow-sm">
        <OrderForm
          onSubmit={handleSubmit}
          onCancel={handleCancel}
          isSubmitting={isSubmitting}
          defaultValues={defaultValues}
          isEditMode
        />
      </div>
    </div>
  );
};

export default EditOrderPage;
